// Writes the host's lines in each persona ("tone") with the language model and
// saves them as content/locales/<locale>/tones/<tone>.json. Run it again after
// adding host lines or a tone:
//
//   node scripts/gen-tones.mjs                 every tone except normal
//   node scripts/gen-tones.mjs sexy therapist  just these
//
// Needs AI_GATEWAY_API_KEY (or another LLM_* setup) in the environment. Every
// line is checked: same {placeholders} as the original, not much longer (lines
// are spoken between phases), so a bad line is dropped and falls back to normal.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildConfig } from '../core/config.js';
import { LLM } from '../core/llm.js';
import { TONES, toneById } from '../core/tones.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LOCALE = process.env.QUIPPY_LOCALE || 'en-AU';
const host = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/locales', LOCALE, 'host.json'), 'utf8')).lines;
const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/locales', LOCALE, 'meta.json'), 'utf8'));

// Labels and exact read-outs stay as they are in every tone.
const SKIP = (k) => /Title|^count\d|^award_|^read(Answers|AnswerA|AnswerB|FinalAnswer)$/.test(k);
// Countdown calls must stay very short.
const TIGHT = new Set(['thirtySeconds', 'tenSeconds', 'answerStart', 'votePreamble', 'unpaused', 'phoneListen', 'answersLocked']);

const holes = (t) => [...new Set(t.match(/\{\w+\}/g) || [])].sort().join(',');

function check(key, originals, line) {
  if (typeof line !== 'string') return false;
  const text = line.trim();
  if (!text) return false;
  const allowed = new Set(originals.map(holes));
  if (!allowed.has(holes(text))) return false;
  const longest = Math.max(...originals.map((o) => o.length));
  const limit = TIGHT.has(key) ? Math.max(28, longest * 1.6) : Math.max(70, longest * 1.7 + 20);
  return text.length <= limit;
}

const config = buildConfig(process.env);
const llm = new LLM({ ...config.llm, timeoutMs: 120000 });
await llm.init();
if (!llm.available()) { console.error('No language model configured (set AI_GATEWAY_API_KEY).'); process.exit(1); }

const wanted = process.argv.slice(2).length ? process.argv.slice(2) : TONES.filter((t) => t.id !== 'normal').map((t) => t.id);
const keys = Object.keys(host).filter((k) => !SKIP(k));
const chunks = [];
for (let i = 0; i < keys.length; i += 14) chunks.push(keys.slice(i, i + 14));

for (const id of wanted) {
  const tone = toneById(id);
  if (tone.id !== id || id === 'normal') { console.error(`Unknown tone ${id}`); continue; }
  const out = {};
  let kept = 0; let dropped = 0;
  await Promise.all(chunks.map(async (chunk) => {
    const source = Object.fromEntries(chunk.map((k) => [k, host[k]]));
    const res = await llm.json({
      system: [
        `You rewrite the spoken lines of Monty, the host of a party comedy game played on a TV with phones as controllers. ${meta.llmHint || ''}`,
        `New persona for this rewrite: ${tone.brief}`,
        'For EVERY key, write 3 to 6 fresh variants in that persona, keeping each line\'s job (what event it announces) and roughly its length: they are spoken aloud between game phases, so keep them punchy. Very short originals stay very short.',
        'Keep every {placeholder} exactly as spelled in the original and use the same set of placeholders as at least one original variant. Do not add new placeholders.',
        'Plain text only: no emoji, no stage directions, no asterisks. Make them genuinely funny.',
        'JSON shape: {"lines":{"<key>":["variant", ...], ...}} with exactly the keys given.',
      ].join('\n'),
      user: JSON.stringify(source),
      maxTokens: 6000,
    });
    for (const k of chunk) {
      const good = (Array.isArray(res?.lines?.[k]) ? res.lines[k] : []).map((t) => String(t).trim()).filter((t) => check(k, host[k], t));
      dropped += (res?.lines?.[k]?.length || 0) - good.length;
      if (good.length) { out[k] = [...new Set(good)]; kept += good.length; }
    }
  }));
  const ordered = Object.fromEntries(keys.filter((k) => out[k]).map((k) => [k, out[k]]));
  const file = path.join(ROOT, 'content/locales', LOCALE, 'tones', `${id}.json`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify({ _comment: `Monty's lines in the "${tone.label}" tone. Generated by scripts/gen-tones.mjs; edit freely. Missing keys fall back to host.json.`, lines: ordered }, null, 2)}\n`);
  console.log(`${id}: ${Object.keys(ordered).length}/${keys.length} events, ${kept} lines kept, ${dropped} dropped -> ${path.relative(ROOT, file)}`);
}
